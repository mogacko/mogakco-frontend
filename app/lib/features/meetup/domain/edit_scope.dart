/// 정기 모각코를 고칠 때 어디까지 미칠지.
///
/// 정기 모임은 매주 월요일 00:00 에 규칙을 보고 그 주 모임이 새로 생긴다.
/// 그래서 이번 주 것을 고쳤을 때 다음 주도 따라갈지가 갈린다 — 이번 주만
/// 카페를 옮긴 것과 아예 옮긴 것은 다른 일이다.
///
/// 어느 쪽을 기본으로 두어도 참여자가 엉뚱한 곳에 간다. 이번 주만으로 두면
/// 폐업한 카페로 다음 주에 가고, 앞으로로 두면 임시로 옮긴 곳에 계속 간다.
/// 둘 다 일주일 뒤에야 드러나므로 기본값을 두지 않고 고르게 한다.
enum EditScope {
  thisWeek('이번 주만', '이번 주 모임만 바뀌어요. 다음 주부터는 원래대로 열려요'),

  /// 이번 주를 포함한다.
  ///
  /// '다음 주부터'라고 적으면 이번 주는 그대로인 줄 알고 반대를 고른다.
  forward('이번 주부터 계속', '이번 주와 앞으로 열릴 모임이 모두 바뀌어요');

  const EditScope(this.label, this.description);

  final String label;
  final String description;
}
